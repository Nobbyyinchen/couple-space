import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
import {spawnSync} from 'node:child_process';
const require=createRequire(import.meta.url),root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const appRoot=path.join(root,'miniprogram'),output=path.resolve(root,'../.runtime/miniprogram-build');
const {wxmlToJs}=require('miniprogram-compiler');
const app=JSON.parse(fs.readFileSync(path.join(appRoot,'app.json'),'utf8'));
const wxml=wxmlToJs(appRoot,{maxBuffer:8*1024*1024});
if(typeof wxml!=='string'||wxml.length<1000)throw Error('WXML compiler returned no code');
const compilerBase=path.dirname(require.resolve('miniprogram-compiler'));
const system=process.platform==='win32'?'windows':process.platform==='darwin'?'mac':'linux';
const binary=path.join(compilerBase,'bin',system,process.platform==='win32'?'wcsc.exe':'wcsc');
const styles=spawnSync(binary,['-db','-pc',String(app.pages.length),...app.pages.map(p=>p+'.wxss'),'app.wxss','theme.wxss'],{cwd:appRoot,encoding:'utf8',maxBuffer:8*1024*1024,windowsHide:true});
if(styles.status!==0)throw Error(styles.stderr||styles.error?.message||'WXSS compilation failed');
fs.mkdirSync(output,{recursive:true});
fs.writeFileSync(path.join(output,'wxml.js'),wxml);
fs.writeFileSync(path.join(output,'wxss.txt'),styles.stdout);
const report={verifiedAt:new Date().toISOString(),compiler:'wechat-miniprogram miniprogram-compiler 0.2.3',pages:app.pages.length,wxmlBytes:Buffer.byteLength(wxml),wxssBytes:Buffer.byteLength(styles.stdout),nativeCompilerPassed:true,devtoolsPreview:false,cloudDeployed:false,phoneTested:false};
fs.writeFileSync(path.join(root,'compile-report.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
